// Builds React icon components from the Growth OS DS v2 Lucide subset
// (design-system/icons/*.svg, ISC) into packages/twenty-front/src/growth-os/icons/gosIcons.generated.ts.
// Consume only: re-run after a DS update (node scripts/growth-os-build-icons.mjs).
import fs from 'node:fs';
import path from 'node:path';

const DS = process.env.GOS_DS_DIR || '/workspace/projects/growth-os/design-system';
const OUT = path.resolve(import.meta.dirname, '../packages/twenty-front/src/growth-os/icons/gosIcons.generated.ts');
const files = fs.readdirSync(path.join(DS, 'icons')).filter((f) => f.endsWith('.svg') && f !== 'sprite.svg').sort();
const nodes = {};
for (const f of files) {
  const svg = fs.readFileSync(path.join(DS, 'icons', f), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '');
  const els = [...inner.matchAll(/<(\w+)([^>]*?)\/?>/g)].map(([, tag, attrs]) => [tag, Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k.replace(/-(\w)/g, (_, c) => c.toUpperCase()), v]))]);
  nodes[f.replace('.svg', '')] = els;
}
const src = `// GENERATED by scripts/growth-os-build-icons.mjs from the Growth OS DS v2 icon
// subset (Lucide, ISC). Do not edit by hand.
export type GosIconNode = [string, Record<string, string>][];

export const GOS_ICON_NODES: Record<string, GosIconNode> = ${JSON.stringify(nodes, null, 1)};
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, src);
console.log('icons', Object.keys(nodes).length, '→', OUT);
