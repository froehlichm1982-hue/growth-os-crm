// Writes the offline common/breached password list into server and front modules.
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const root = join(__dirname, '..');
const words = readFileSync(join(root, 'scripts/growth-os-data/common-passwords-8plus.txt'), 'utf8')
  .split('\n')
  .map((w) => w.trim())
  .filter(Boolean);
const body = `// GENERATED by scripts/growth-os-generate-password-list.ts — do not edit.\n// Source: scripts/growth-os-data (SecLists, MIT). ${words.length} entries, lower-case, 8–64 chars.\n// oxlint-disable\n// prettier-ignore\nexport const GROWTH_OS_COMMON_PASSWORDS: string = ${JSON.stringify(words.join('\n'))};\n`;

writeFileSync(join(root, 'packages/twenty-server/src/engine/core-modules/growth-os/password/growth-os-common-passwords.generated.ts'), body);
writeFileSync(join(root, 'packages/twenty-front/src/growth-os/auth/growthOsCommonPasswords.generated.ts'), body);
console.log('wrote', words.length);
