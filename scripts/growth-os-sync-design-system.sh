#!/bin/bash
# Copies the generated Growth OS Design System v2 files into the front (MIGRATION.md §2.1).
# Consume only: never edit packages/twenty-front/src/gos/* by hand; re-run this script instead.
set -euo pipefail
DS=${GOS_DS_DIR:-/workspace/projects/growth-os/design-system}
FRONT=$(cd "$(dirname "$0")/../packages/twenty-front" && pwd)
OUT=$FRONT/src/gos
mkdir -p "$OUT/generated" "$OUT/fonts" "$OUT/css"
# DS v2.9: the CRM does NOT load generated/tokens.css or css/gos.css (they style html/body/*). It loads the
# CRM-scoped build instead (every rule under .gos, fonts renamed "GOS Geist*"), generated here from the DS on
# every release. Never edit packages/twenty-front/src/gos/css/gos.scoped.css by hand (docs/SCOPED-CSS.md in the DS).
rm -f "$OUT/generated/tokens.css"
for f in crm-theme.mjs crm-theme.d.mts tokens.mjs tokens.email.json; do [ -f "$DS/generated/$f" ] && cp "$DS/generated/$f" "$OUT/generated/$f"; done
python3 "$DS/scripts/build_scoped.py" --root .gos --out "$OUT/css/gos.scoped.css"
# Auth art panel (DS v2.9 demo product card: Pipeline + Timeline, Nordlicht Analytics demo data, no photos).
mkdir -p "$FRONT/public/images/growth-os/auth"
for f in r-col r-time; do for ext in avif webp; do for r in 1x 2x; do cp "$DS/assets/auth/$f@$r.$ext" "$FRONT/public/images/growth-os/auth/$f@$r.$ext"; done; done; done
cp "$DS/fonts/Geist-Variable.woff2" "$DS/fonts/GeistMono-Variable.woff2" "$DS/fonts/LICENSE-Geist-OFL.txt" "$OUT/fonts/"
cp "$DS/icons/LICENSE-Lucide-ISC.txt" "$OUT/"
for f in favicon-512.png logo-light@2x.png logo-dark@2x.png; do cp "$DS/assets/$f" "$FRONT/public/images/growth-os/$f"; done
# Email base (CONTENT.md §4, email/base.html): tokens for the React mail kit + header art.
EMAILS=$(cd "$(dirname "$0")/../packages/twenty-emails" && pwd)
mkdir -p "$EMAILS/src/gos"
cp "$DS/generated/tokens.email.json" "$EMAILS/src/gos/tokens.email.json"
node --input-type=module -e "
import fs from 'node:fs';
const email = JSON.parse(fs.readFileSync('$DS/generated/tokens.email.json', 'utf8'));
const t = await import('$DS/generated/tokens.mjs');
const edge = (k) => ({ info: k['info-fill'], danger: k['danger-fill'], warning: k['warning-fill'], success: k['success-fill'] });
const out = { ...email, edge: { light: edge(t.light), dark: edge(t.dark) } };
fs.writeFileSync('$EMAILS/src/gos/tokensEmail.generated.ts', '// GENERATED by scripts/growth-os-sync-design-system.sh from DS generated/tokens.email.json + tokens.mjs (status fills). Do not edit.\\nexport const GOS_EMAIL = ' + JSON.stringify(out, null, 2) + ' as const;\\n');
"
for f in header-crm-light@2x.png header-crm-dark@2x.png; do cp "$DS/email/assets/$f" "$FRONT/public/images/growth-os/email-$f"; done
( cd "$DS" && git rev-parse --short HEAD 2>/dev/null || date +%F ) > "$OUT/DS-VERSION"
grep -o 'Design System v[0-9.]*' "$DS/generated/tokens.css" | head -1 >> "$OUT/DS-VERSION"
echo "synced DS into $OUT"
